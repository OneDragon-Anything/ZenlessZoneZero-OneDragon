def parse_catalog(path: Path) -> tuple[list[str], dict[str, str]]:
    """Read a PO catalog while preserving its message order."""
    values, duplicates = read_catalog(path)
    if duplicates:
        raise ValueError(f'Duplicate msgids in {path}: {sorted(duplicates)}')
    return list(values), values


def quote(value: str) -> str:
    """Quote a PO string without escaping Unicode characters."""
    return json.dumps(value, ensure_ascii=False)


def write_catalog(path: Path, order: list[str], values: dict[str, str]) -> None:
    """Write a deterministic single-line catalog."""
    missing = [msgid for msgid in order if msgid and msgid not in values]
    if missing:
        raise ValueError(f'Cannot write {path}: missing translations for {missing}')
    lines = [
        'msgid ""',
        'msgstr "Content-Type: text/plain; charset=UTF-8\\nContent-Transfer-Encoding: 8bit\\n"',
        '',
    ]
    for msgid in order:
        if not msgid:
            continue
        lines.append(f'msgid {quote(msgid)}')
        lines.append(f'msgstr {quote(values[msgid])}')
        lines.append('')
    path.write_text('\n'.join(lines), encoding='utf-8')


def main() -> None:
    """Merge the translation batch into all supported catalogs."""
    paths = {
        'en': CATALOG_DIR / 'en.po',
        'zh': CATALOG_DIR / 'zh.po',
        'vi': CATALOG_DIR / 'vi.po',
    }
    parsed = {language: parse_catalog(path) for language, path in paths.items()}
    all_ids: list[str] = []
    known_ids: set[str] = set()
    for language in paths:
        for msgid in parsed[language][0]:
            if msgid not in known_ids:
                all_ids.append(msgid)
                known_ids.add(msgid)
    for msgid in ENGLISH_TRANSLATIONS:
        if msgid not in known_ids:
            all_ids.append(msgid)
            known_ids.add(msgid)

    for language, path in paths.items():
        _, values = parsed[language]
        for msgid, english in ENGLISH_TRANSLATIONS.items():
            if language == 'en':
                values[msgid] = english
            elif language == 'zh':
                values[msgid] = msgid
            else:
                values[msgid] = values.get(msgid, english)
        for msgid in all_ids:
            if msgid in values:
                continue
            english = ENGLISH_TRANSLATIONS.get(
                msgid,
                parsed['en'][1].get(msgid, msgid),
            )
            values[msgid] = msgid if language == 'zh' else english
        write_catalog(path, all_ids, values)


if __name__ == '__main__':
    main()
